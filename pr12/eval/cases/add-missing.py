def merge(path: Path, extras: list[dict]) -> None:
    if not path.exists():
        print(f"{path}: НЕ ІСНУЄ — пропускаю")
        return
    base = json.loads(path.read_text(encoding="utf-8"))
    base_ids = {c["id"] for c in base}
    added = [c for c in extras if c["id"] not in base_ids]
    skipped = [c["id"] for c in extras if c["id"] in base_ids]
    path.write_text(json.dumps(base + added, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"{path.name}: {len(base)} + {len(added)} = {len(base) + len(added)}"
          + (f" (уже були: {skipped})" if skipped else ""))


